"""Package stage: bind the model to its provenance in a manifest + model card.

The manifest is what the serving container trusts. It records the model's
SHA-256, the exact training data digest, the commit, library versions and
the gate metrics. CI later signs the container image and attaches this file
as a Cosign attestation, so production can prove which data and code
produced the model it is running.
"""

from __future__ import annotations

import json
import os
import platform
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import sklearn
import skops

from fraudguard import __version__
from fraudguard.features import MODEL_FEATURES, RAW_FEATURES
from fraudguard.integrity import sha256_file


def git_commit(root: Path) -> str:
    """Resolve HEAD without shelling out (CI sets GITHUB_SHA)."""
    if sha := os.environ.get("GITHUB_SHA"):
        return sha
    head = root / ".git" / "HEAD"
    try:
        ref = head.read_text().strip()
        if ref.startswith("ref: "):
            ref_path = root / ".git" / ref[5:]
            if ref_path.exists():
                return ref_path.read_text().strip()
            packed = (root / ".git" / "packed-refs").read_text().splitlines()
            for line in packed:
                if line.endswith(ref[5:]):
                    return line.split()[0]
        return ref
    except OSError:
        return "unknown"


def build_manifest(
    model_path: Path,
    train_path: Path,
    metrics: dict[str, Any],
    params: dict[str, Any],
    root: Path,
) -> dict[str, Any]:
    return {
        "name": "fraudguard",
        "version": __version__,
        "created_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "model": {
            "file": model_path.name,
            "format": "skops",
            "sha256": sha256_file(model_path),
            "threshold": metrics["threshold"],
        },
        "features": {"raw": RAW_FEATURES, "model": MODEL_FEATURES},
        "data": {"train_file": train_path.as_posix(), "train_sha256": sha256_file(train_path)},
        "metrics": metrics,
        "params": {"seed": params["seed"], "train": params["train"]},
        "provenance": {
            "git_commit": git_commit(root),
            "python": platform.python_version(),
            "scikit_learn": sklearn.__version__,
            "skops": skops.__version__,
        },
    }


def render_model_card(manifest: dict[str, Any]) -> str:
    m = manifest["metrics"]
    slices = "\n".join(f"| {k} | {v} |" for k, v in m["slice_recall"].items())
    return f"""# Model card: FraudGuard {manifest["version"]}

Generated by the `package` pipeline stage on {manifest["created_at"]}.

## Intended use
Score card transactions for fraud risk to **prioritise human review**.
Not approved for fully automated card blocking or customer-facing decisions
without a human in the loop.

## Model
- Gradient-boosted trees (scikit-learn `HistGradientBoostingClassifier`),
  one-hot merchant encoding
- Serialized with skops, SHA-256 `{manifest["model"]["sha256"]}`
- Decision threshold `{m["threshold"]}` chosen on the validation split for precision >= target

## Training data
Synthetic, seeded transaction data (no real cardholder data, no PII).
Train split digest `{manifest["data"]["train_sha256"]}`.

## Test-split performance
| Metric | Value |
|---|---|
| ROC-AUC | {m["roc_auc"]} |
| PR-AUC | {m["pr_auc"]} |
| Precision @ threshold | {m["precision"]} |
| Recall @ threshold | {m["recall"]} |

## Slice recall (fraud caught per channel)
| Slice | Recall |
|---|---|
{slices}

## Known limitations
- Trained on synthetic patterns; real deployments must retrain on governed production data.
- New fraud patterns (concept drift) degrade recall silently until labels arrive. The drift
  monitor and the weekly drift workflow exist to surface this early.
- Probability scores are not calibrated; use the threshold, not the raw score, for decisions.

## Provenance
- Commit `{manifest["provenance"]["git_commit"]}`
- Python {manifest["provenance"]["python"]}, scikit-learn {manifest["provenance"]["scikit_learn"]},
  skops {manifest["provenance"]["skops"]}
"""


def write_package(model_dir: Path, manifest: dict[str, Any]) -> None:
    (model_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (model_dir / "MODEL_CARD.md").write_text(render_model_card(manifest))


def log_to_mlflow(model_dir: Path, manifest: dict[str, Any]) -> str | None:
    """Record the run in MLflow (params, gate metrics, signed-off artifacts)."""
    try:
        import mlflow
    except ImportError:
        return None

    os.environ.setdefault("MLFLOW_TRACKING_URI", "sqlite:///mlflow.db")
    os.environ.setdefault("MLFLOW_DISABLE_AGENT_HINT", "1")
    mlflow.set_experiment("fraudguard")
    m = manifest["metrics"]
    with mlflow.start_run(run_name=f"fraudguard-{manifest['model']['sha256'][:12]}") as run:
        mlflow.log_params({"seed": manifest["params"]["seed"], **manifest["params"]["train"]})
        mlflow.log_metrics(
            {k: m[k] for k in ("roc_auc", "pr_auc", "precision", "recall", "slice_recall_gap")}
        )
        mlflow.set_tags(
            {
                "git_commit": manifest["provenance"]["git_commit"],
                "model_sha256": manifest["model"]["sha256"],
                "data_sha256": manifest["data"]["train_sha256"],
                "serialization": "skops",
            }
        )
        for name in (manifest["model"]["file"], "manifest.json", "MODEL_CARD.md"):
            mlflow.log_artifact(str(model_dir / name), artifact_path="model")
        return run.info.run_id
